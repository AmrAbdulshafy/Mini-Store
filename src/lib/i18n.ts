export function formatPrice(amount: number, currency: string, lang: Language): string {
  const formatted = new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-EG', {
    maximumFractionDigits: 0,
  }).format(amount);
  if (lang === 'ar') {
    return `${formatted} ${currency === 'EGP' ? 'ج.م' : currency}`;
  }
  return `${formatted} ${currency}`;
}

export function getCollectionLabel(slug: CollectionSlug | string, lang: Language): string {
  if (slug === 'women') return lang === 'ar' ? 'المرأة' : 'Women';
  if (slug === 'men') return lang === 'ar' ? 'الرجل' : 'Men';
  if (slug === 'handmade') return lang === 'ar' ? 'الأعمال اليدوية' : 'Handmade';
  return slug;
}
